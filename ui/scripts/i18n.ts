// Writes src/app/i18n/strings.g.ts, the type of the app's strings, from src/app/i18n/en.i18n.json: a text with
// parameters becomes a function of them, a plural a function of `n` and the parameters its forms use. Run it after
// changing the English file:
//
//   bun scripts/i18n.ts          # rewrite the types
//   bun scripts/i18n.ts --check  # exit 1 when they are stale (`bun run typecheck` runs this)
import { isPlural, keyName, parseText, pluralParam } from "../src/app/i18n/slang";

const source = new URL("../src/app/i18n/en.i18n.json", import.meta.url);
const target = new URL("../src/app/i18n/strings.g.ts", import.meta.url);

function typeOf(node: unknown, path: string, indent: string): string {
  if (typeof node === "string") return functionType(parseText(node).params, false);
  if (Array.isArray(node)) {
    if (!node.every((item) => typeof item === "string")) throw new Error(`${path}: a list holds only plain strings`);
    return "readonly string[]";
  }
  if (typeof node !== "object" || node === null) throw new Error(`${path}: not a string, list or object`);
  if (isPlural(node)) {
    const params = new Set<string>();
    for (const form of Object.values(node)) for (const param of parseText(form).params) params.add(param);
    params.delete(pluralParam);
    return functionType([...params], true);
  }
  const inner = `${indent}  `;
  const fields = Object.entries(node).map(([key, value]) => {
    const name = keyName(key);
    return `${inner}readonly ${name}: ${typeOf(value, `${path}.${name}`, inner)};`;
  });
  return `{\n${fields.join("\n")}\n${indent}}`;
}

function functionType(params: readonly string[], plural: boolean): string {
  const fields = [...(plural ? [`${pluralParam}: number`] : []), ...[...new Set(params)].map((name) => `${name}: Param`)];
  return fields.length === 0 ? "string" : `(args: { ${fields.join("; ")} }) => string`;
}

const english: unknown = JSON.parse(await Bun.file(source).text());
const text = `// Generated by \`bun scripts/i18n.ts\` from src/app/i18n/en.i18n.json. Do not edit.

/** A parameter's value; the text holds \`String(value)\`. */
export type Param = string | number;

export type Translations = ${typeOf(english, "", "")};
`;

if (process.argv.includes("--check")) {
  const current = await Bun.file(target).text();
  if (current !== text) {
    console.error("src/app/i18n/strings.g.ts is stale: run `bun scripts/i18n.ts` in ui/");
    process.exit(1);
  }
} else {
  await Bun.write(target, text);
}
